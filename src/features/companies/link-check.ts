/**
 * Rules for checking a company's official careers page. Pure functions: the CLI in
 * scripts/check-career-links.ts does the fetching and writes the result module.
 *
 * A page is accepted only when all of these hold (the Nov 17, 2026 standard in
 * docs/phase3/opportunities-data-model.md):
 * - the final response, after redirects, is HTTP 200 over https
 * - the final host is the company's own domain (hostSuffix), never a job board
 * - the page title or opening text reads like a careers page, not an error page
 */

export type CareerLinkCheck = {
  companyId: string;
  requestedUrl: string;
  /** Null when the request failed before any response. */
  finalUrl: string | null;
  finalHost: string | null;
  httpStatus: number | null;
  title: string | null;
  checkedOn: string;
  accepted: boolean;
  /** Why a page was rejected. Null when accepted. */
  reason: string | null;
};

export const CHECK_METHOD =
  "One HTTP GET per URL with a browser User-Agent, redirects followed, run by scripts/check-career-links.ts. Accepted only when the final status is 200 over https, the final host belongs to the organization, and the page title or opening text identifies a careers page. Nothing fetches these on a schedule.";

/** Re-check links older than this; older links stop being shown. */
export const CHECK_MAX_AGE_DAYS = 90;

export const JOB_BOARD_HOSTS = [
  "linkedin.com",
  "indeed.com",
  "greenhouse.io",
  "lever.co",
  "handshake.com",
  "joinhandshake.com",
  "ziprecruiter.com",
  "glassdoor.com",
] as const;

const CAREERS_WORDS = /career|job|opportunit|join (?:our|the) team|work (?:with|at|for) us|hiring|talent|employment|internship/i;
const ERROR_WORDS = /\b404\b|not found|page (?:doesn'?t|does not|cannot be|can't be) (?:exist|found)|no longer available|access denied|forbidden/i;

export function hostMatches(host: string, suffix: string): boolean {
  return host === suffix || host.endsWith(`.${suffix}`);
}

export function isJobBoard(host: string): boolean {
  return JOB_BOARD_HOSTS.some((board) => hostMatches(host, board));
}

/** The text of the first <title>, whitespace collapsed, or null. */
export function pageTitle(html: string): string | null {
  const match = /<title[^>]*>([\s\S]*?)<\/title>/i.exec(html);
  if (!match) return null;
  const text = match[1]
    .replace(/&amp;/g, "&")
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, " ")
    .trim();
  return text.length > 0 ? text.slice(0, 200) : null;
}

/** Visible-ish text from the start of the body, for the careers-page test. */
export function openingText(html: string, limit = 4000): string {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, limit);
}

export function judgeCheck(input: {
  hostSuffix: string;
  finalUrl: string | null;
  httpStatus: number | null;
  html: string;
}): { accepted: boolean; reason: string | null } {
  if (input.httpStatus === null || input.finalUrl === null) return { accepted: false, reason: "no response" };
  if (input.httpStatus !== 200) return { accepted: false, reason: `HTTP ${input.httpStatus}` };
  let url: URL;
  try {
    url = new URL(input.finalUrl);
  } catch {
    return { accepted: false, reason: "final URL did not parse" };
  }
  if (url.protocol !== "https:") return { accepted: false, reason: "final URL is not https" };
  if (isJobBoard(url.host)) return { accepted: false, reason: `job board host ${url.host}` };
  if (!hostMatches(url.host, input.hostSuffix)) {
    return { accepted: false, reason: `final host ${url.host} is not on ${input.hostSuffix}` };
  }
  const title = pageTitle(input.html) ?? "";
  if (ERROR_WORDS.test(title)) return { accepted: false, reason: "title reads like an error page" };
  if (!CAREERS_WORDS.test(title) && !CAREERS_WORDS.test(openingText(input.html))) {
    return { accepted: false, reason: "page does not read like a careers page" };
  }
  return { accepted: true, reason: null };
}

/** Whole days between a YYYY-MM-DD date and today (UTC). */
export function ageInDays(checkedOn: string, today: Date): number {
  const then = Date.UTC(
    Number(checkedOn.slice(0, 4)),
    Number(checkedOn.slice(5, 7)) - 1,
    Number(checkedOn.slice(8, 10)),
  );
  const now = Date.UTC(today.getUTCFullYear(), today.getUTCMonth(), today.getUTCDate());
  return Math.floor((now - then) / 86_400_000);
}

/** The generated module, sorted by company id so re-runs diff cleanly. */
export function renderChecksModule(checks: readonly CareerLinkCheck[]): string {
  const sorted = [...checks].sort((left, right) => left.companyId.localeCompare(right.companyId));
  const rows = sorted.map((check) => `  ${JSON.stringify(check)},`).join("\n");
  return `// GENERATED by scripts/check-career-links.ts. Do not edit by hand; re-run the script.
// Accepted rows are the only careers links Swervly shows. Rejected rows stay as a record.
import type { CareerLinkCheck } from "@/features/companies/link-check";

export const CAREER_LINK_CHECKS: readonly CareerLinkCheck[] = [
${rows}
];
`;
}
