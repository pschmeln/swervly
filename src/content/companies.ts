/**
 * Every company Swervly knows about, in one list (Nov 21, 2026).
 *
 * - The co-op form's employers come from here: scripts/seed-employers.ts upserts every
 *   entry as an approved employer, matched by normalizeEmployerName(name).
 * - Companies & opportunities and the career map list an entry only when its careers
 *   page passed a check in src/content/career-link-checks.ts.
 *
 * Fields
 * - id: stable slug. Never reuse or rename one; reviews and posts may point at it later.
 * - name: canonical display name. Changing it in a way that changes the normalized name
 *   creates a second employer row; add the old name to aliases instead.
 * - city: headquarters, "City, ST". Null means not verified, not "no location".
 *   A co-op's work location belongs to the rotation, not to this field.
 * - roleTypes: kinds of co-op and internship work, as Direction's career role ids.
 * - families: career map families the company is listed under. Never a hiring claim.
 * - careers: the official careers page to check, and the domain the final URL must stay on.
 *
 * Sources: the first 51 entries came from UC CEAS public pages (see git history of
 * employers-seed.ts); the 12 directory organizations from the Nov 17, 2026 link check.
 * Do not copy lists from Handshake, LinkedIn or any university system.
 */
